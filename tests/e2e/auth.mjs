// D묶음 22번: 서버 간 요청 서명
import { call, AS, KEYS } from './sign.mjs'
const FT = 'http://localhost:8080', STAR = 'http://localhost:8081'
let fails = 0
const check = (n, c, x = '') => { console.log(`${c ? 'PASS' : 'FAIL'}  ${n} ${x}`); if (!c) fails++ }
const err = (r) => `${r.status} ${r.data?.error ?? ''}`

console.log('--- 예매처 /ft/* : FairTicket 만 ---')
let r = await call('GET', `${STAR}/ft/tickets/1`)
check('서명 없는 조회 거절', r.status === 401, err(r))
r = await call('POST', `${STAR}/ft/tickets/1/reissue`, { newOwnerFtUid: 'ft-u-bot' }, { idem: 'atk-1' })
check('서명 없는 "내 계정으로 재발급" 공격 거절', r.status === 401, err(r))
r = await call('POST', `${STAR}/ft/tickets/1/reissue`, { newOwnerFtUid: 'ft-u-bot' }, { idem: 'atk-2', signAs: { client: 'fairticket', secret: 'guessed-secret' } })
check('추측한 비밀키로 서명 → 거절', r.status === 401, err(r))
r = await call('POST', `${STAR}/ft/tickets/1/reissue`, { newOwnerFtUid: 'ft-u-bot' }, { idem: 'atk-3', signAs: AS.star })
check('예매처 자기 키로 /ft/* 호출 → 거절 (FairTicket 만 가능)', r.status === 401, err(r))
r = await call('POST', `${STAR}/ft/tickets/1/reissue`, { newOwnerFtUid: 'ft-u-002' }, { idem: 'atk-4', signAs: AS.ftToMoon })
check('달티켓용 키로 별티켓 호출 → 거절 (발행처별 키 분리)', r.status === 401, err(r))
r = await call('GET', `${STAR}/ft/tickets/1`, undefined, { signAs: AS.ftToStar })
check('올바른 FairTicket 서명 → 인증 통과 (빈 DB라 404)', r.status !== 401, err(r))
r = await call('POST', `${STAR}/ft/tickets/1/lock`, {}, { idem: 'atk-5', signAs: AS.ftToStar, tamperBody: { x: 1 } })
check('서명 후 본문 변조 → 거절', r.status === 401, err(r))
const old = String(Math.floor(Date.now() / 1000) - 600)
r = await call('GET', `${STAR}/ft/tickets/1`, undefined, { signAs: AS.ftToStar, ts: old })
check('10분 전 시각의 요청 → 거절', r.status === 401, err(r))
const nonce = 'fixed-nonce-' + Date.now()
r = await call('GET', `${STAR}/ft/tickets/1`, undefined, { signAs: AS.ftToStar, nonce })
const r2 = await call('GET', `${STAR}/ft/tickets/1`, undefined, { signAs: AS.ftToStar, nonce })
check('가로챈 요청 그대로 재전송 → 거절', r.status !== 401 && r2.status === 401, `${r.status} → ${err(r2)}`)

console.log('--- FairTicket 예매처 전용 API ---')
const ev = { vendorId: 'star', uid: 'ft-u-003', performanceCode: 'PERF-001', result: 'ATTEMPT', ip: '1.1.1.1', reactionMs: 3000 }
r = await call('POST', `${FT}/v1/purchase-events`, ev)
check('서명 없는 거짓 구매 기록 → 거절', r.status === 401, err(r))
r = await call('GET', `${FT}/v1/risk?uid=ft-u-003&performanceCode=PERF-001`)
check('서명 없는 위험 점수 조회 → 거절', r.status === 401, err(r))
r = await call('POST', `${FT}/v1/quota/reserve`, { uid: 'ft-u-003', performanceCode: 'PERF-001', vendorId: 'star', qty: 2, limit: 2 })
check('서명 없이 남의 한도 소진 시도 → 거절', r.status === 401, err(r))
r = await call('POST', `${FT}/v1/resales`, { vendorId: 'star', vendorTicketId: 1, performanceCode: 'PERF-001', sellerUid: 'x', price: 1, startsAt: '2099-01-01T00:00:00' })
check('서명 없는 재판매 등록 → 거절', r.status === 401, err(r))
r = await call('POST', `${FT}/v1/captcha/verify`, { id: 'x', answer: '1' })
check('서명 없는 보안문자 확인 → 거절', r.status === 401, err(r))
r = await call('POST', `${FT}/v1/purchase-events`, ev, { signAs: AS.star })
check('별티켓 서명 → 기록 허용', r.status === 200, err(r))
r = await call('POST', `${FT}/v1/purchase-events`, { ...ev, vendorId: 'moon' }, { signAs: AS.star })
check('별티켓이 달티켓 이름으로 기록 → 403', r.status === 403, err(r))
r = await call('POST', `${FT}/v1/purchase-events`, ev, { signAs: { client: 'moon', secret: KEYS.star } })
check('별티켓 키로 "나는 달티켓" 위장 → 401', r.status === 401, err(r))
r = await call('POST', `${FT}/v1/quota/reserve`, { uid: 'ft-u-auth', performanceCode: 'PERF-001', vendorId: 'star', qty: 1, limit: 2 }, { signAs: AS.star })
check('별티켓 한도 예약', r.status === 200, err(r))
const resId = r.data.id
r = await call('POST', `${FT}/v1/quota/${resId}/release`, undefined, { signAs: AS.moon })
check('달티켓이 별티켓 예약을 반환 → 403', r.status === 403, err(r))
r = await call('POST', `${FT}/v1/quota/${resId}/release`, undefined, { signAs: AS.star })
check('별티켓이 자기 예약 반환 → 허용', r.status === 200, err(r))
r = await call('GET', `${FT}/v1/risk?uid=ft-u-003&performanceCode=PERF-001`, undefined, { signAs: AS.star })
check('서명한 위험 조회 (쿼리 포함 서명) → 허용', r.status === 200 && r.data.riskLevel, err(r))

console.log('--- 화면용 API 와 시연 경로 ---')
r = await call('GET', `${FT}/v1/resales`)
check('화면용 재판매 목록은 그대로 열림', r.status === 200)
r = await call('POST', `${FT}/v1/demo/purchase-events`, ev)
check('시연 도구 경로(시연 모드) 동작', r.status === 200, err(r))
r = await call('GET', `${FT}/v1/demo/risk?uid=ft-u-003&performanceCode=PERF-001`)
check('시연용 위험 조회 동작', r.status === 200 && r.data.riskLevel)
console.log(`\n${fails === 0 ? 'ALL PASS' : fails + ' FAILED'}`)
process.exit(fails ? 1 : 0)
